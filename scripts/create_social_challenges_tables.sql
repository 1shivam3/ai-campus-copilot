    ADD COLUMN IF NOT EXISTS bonus_questions_completed INTEGER DEFAULT 0;


-- 5. Safe Public Learning Profiles View (Zero Personal Private Data)
CREATE OR REPLACE VIEW public.public_learning_profiles AS
SELECT 
    p.id AS user_id,
    COALESCE(
        p.public_display_name,
        CASE WHEN p.is_public = TRUE THEN p.full_name ELSE 'Learner_' || SUBSTRING(p.id::text, 1, 6) END
    ) AS display_name,
    CASE WHEN p.is_public = TRUE THEN p.avatar_url ELSE NULL END AS avatar_url,
    COALESCE(p.reputation, 50) AS reputation,
    COALESCE(p.current_streak, 0) AS current_streak,
    COALESCE(p.longest_streak, 0) AS longest_streak,
    COALESCE(SUM(tx.amount), 0)::INTEGER AS total_xp,
    COUNT(DISTINCT ch.id) AS challenges_solved
FROM public.student_profiles p
LEFT JOIN public.xp_transactions tx ON tx.user_id = p.id
LEFT JOIN public.user_challenge_history ch ON ch.user_id = p.id AND ch.passed = TRUE
GROUP BY p.id, p.public_display_name, p.full_name, p.avatar_url, p.is_public, p.reputation, p.current_streak, p.longest_streak;
